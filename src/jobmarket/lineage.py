"""The dbt lineage graph as a Mermaid diagram (docs/lineage.md), generated from the dbt manifest.

A hand-drawn lineage drifts from the code; this one is built by `dbt parse` and a test fails when
`docs/lineage.md` differs from what the project says today. Regenerate with `make lineage`.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

LINEAGE_FILE = Path("docs/lineage.md")
PROJECT_DIR = Path("warehouse")

# (title, how to recognise a node) in the order the subgraphs are drawn
_LAYERS = (
    ("sources", "Silver tables written by the Python pipeline"),
    ("seeds", "Seeds (CSV vocabularies)"),
    ("snapshots", "Snapshots (SCD2)"),
    ("staging", "Staging"),
    ("intermediate", "Intermediate"),
    ("marts", "Marts (exported as parquet)"),
)


def _layer(node: dict[str, Any]) -> str:
    kind = node["resource_type"]
    if kind == "seed":
        return "seeds"
    if kind == "snapshot":
        return "snapshots"
    return str(node["original_file_path"]).split("/")[1]  # models/<layer>/<file>.sql


def _node_id(unique_id: str) -> str:
    return (
        unique_id.split(".")[-1]
        if not unique_id.startswith("source.")
        else ("src_" + unique_id.split(".")[-1])
    )


def build_mermaid(manifest: dict[str, Any]) -> str:
    """Mermaid ``graph LR`` of models, seeds, snapshots and sources and the edges between them."""
    nodes: dict[str, dict[str, Any]] = {}
    for unique_id, node in manifest["nodes"].items():
        if node["resource_type"] in ("model", "seed", "snapshot"):
            nodes[unique_id] = {**node, "layer": _layer(node)}
    for unique_id, source in manifest["sources"].items():
        nodes[unique_id] = {**source, "layer": "sources", "name": source["name"]}

    lines = ["graph LR"]
    for layer, title in _LAYERS:
        members = sorted((u for u, n in nodes.items() if n["layer"] == layer), key=_node_id)
        if not members:
            continue
        lines.append(f'  subgraph {layer}["{title}"]')
        lines += [f"    {_node_id(u)}[{nodes[u]['name']}]" for u in members]
        lines.append("  end")

    edges = sorted(
        (_node_id(parent), _node_id(child))
        for child in nodes
        for parent in manifest["parent_map"].get(child, [])
        if parent in nodes
    )
    lines += [f"  {parent} --> {child}" for parent, child in edges]
    return "\n".join(lines)


def render_page(manifest: dict[str, Any]) -> str:
    return (
        "# dbt lineage\n\n"
        "Generated by `make lineage` from the dbt manifest; a test fails when it is out of date.\n"
        "Arrows go from a table to the models that read it.\n\n"
        f"```mermaid\n{build_mermaid(manifest)}\n```\n"
    )


def load_manifest(project_dir: Path = PROJECT_DIR) -> dict[str, Any]:
    """Run `dbt parse` into a temporary target and read its manifest (no data is needed)."""
    dbt = Path(sys.executable).parent / "dbt"
    with tempfile.TemporaryDirectory() as folder:
        env = {
            "PATH": str(dbt.parent) + os.pathsep + os.environ.get("PATH", ""),
            "DUCKDB_PATH": str(Path(folder) / "lineage.duckdb"),
            "DBT_TARGET_PATH": str(Path(folder) / "target"),
        }
        subprocess.run(
            [
                str(dbt),
                "parse",
                "--project-dir",
                str(project_dir),
                "--profiles-dir",
                str(project_dir),
            ],
            check=True,
            capture_output=True,
            env=env,
        )
        loaded: dict[str, Any] = json.loads(
            (Path(folder) / "target" / "manifest.json").read_text(encoding="utf-8")
        )
        return loaded


if __name__ == "__main__":
    LINEAGE_FILE.write_text(render_page(load_manifest()), encoding="utf-8")
    print(f"wrote {LINEAGE_FILE}")
